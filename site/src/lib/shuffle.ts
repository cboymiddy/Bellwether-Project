// Seeded shuffling for the demo: exactly nTrue of the 32 years are "true"; the same seed gives the same sequence.
export function hashSeed(s: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return h >>> 0;
}
export function mulberry32(seed: number): () => number {
  let a = seed | 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
export function randomTarget(rng: () => number, nTrue: number): number {
  const idx = Array.from({ length: 32 }, (_, i) => i);
  for (let i = 31; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [idx[i], idx[j]] = [idx[j], idx[i]]; }
  let t = 0;
  for (let i = 0; i < nTrue; i++) t = (t | (1 << idx[i])) >>> 0;
  return t;
}
export function popcount(x: number): number {
  let c = 0;
  for (let v = x >>> 0; v; v &= v - 1) c++;
  return c;
}
export function wilson(k: number, n: number, z = 1.96): [number, number] {
  if (n === 0) return [0, 1];
  const p = k / n, d = 1 + (z * z) / n, c = (p + (z * z) / (2 * n)) / d;
  const h = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / d;
  return [Math.max(0, c - h), Math.min(1, c + h)];
}
